import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';

import { findPendingFields, isCanonicalUtcIso } from './release-manifest.mjs';

function sha256(body) {
  return createHash('sha256').update(body).digest('hex');
}

export function cosAuthoritySha256(authority) {
  return sha256(`${JSON.stringify(authority, null, 2)}\n`);
}

export function cosUploadLedgerSha256(ledger) {
  return sha256(`${JSON.stringify(ledger, null, 2)}\n`);
}

export function buildCosAuthority(manifest, feedBodies) {
  const objects = manifest.publication.cosObjects.map((spec) => {
    if (spec.phase === 'payload') {
      const asset = manifest.assets[spec.assetKey];
      return {
        order: spec.order,
        phase: spec.phase,
        key: asset.fileName,
        bytes: asset.sizeBytes,
        sha256: asset.sha256,
      };
    }
    const body = feedBodies[spec.feedKey];
    if (typeof body !== 'string') throw new Error(`Missing rendered feed body: ${spec.feedKey}`);
    return {
      order: spec.order,
      phase: spec.phase,
      key: spec.key,
      bytes: Buffer.byteLength(body),
      sha256: sha256(body),
    };
  });
  return {
    schemaVersion: 1,
    version: manifest.version,
    baseUrl: manifest.origins.cos,
    sequencing: 'payload-first-metadata-last',
    objects,
  };
}

export function buildManualCosAuthority(manifest) {
  const full = buildCosAuthority(manifest, { darwinArm64: '' });
  return {
    ...full,
    sequencing: 'manual-payloads-only',
    objects: full.objects.slice(0, 2),
  };
}

export function loadCosEvidence(path, envName = 'OCUPATH_COS_EVIDENCE_JSON') {
  if (!path) throw new Error(`${envName} is required`);
  return JSON.parse(readFileSync(path, 'utf8'));
}

export function loadCosUploadLedger(path, envName = 'OCUPATH_COS_UPLOAD_LEDGER_JSON') {
  if (!path) throw new Error(`${envName} is required`);
  return JSON.parse(readFileSync(path, 'utf8'));
}

export function validateCosUploadLedger(authority, ledger) {
  const failures = [];
  if (ledger?.schemaVersion !== 1) failures.push('COS upload ledger schemaVersion must be 1');
  if (ledger?.version !== authority.version) failures.push('COS upload ledger version mismatch');
  if (ledger?.baseUrl !== authority.baseUrl) failures.push('COS upload ledger baseUrl mismatch');
  if (ledger?.sequencing !== authority.sequencing) failures.push('COS upload ledger sequencing mismatch');
  if (ledger?.authoritySha256 !== cosAuthoritySha256(authority)) failures.push('COS upload ledger authority digest mismatch');
  if (findPendingFields(ledger).length > 0) failures.push('COS upload ledger contains pending placeholders');
  const actual = ledger?.objects ?? [];
  if (actual.length !== authority.objects.length) {
    failures.push(`COS upload ledger object count mismatch: ${actual.length}/${authority.objects.length}`);
  }
  let priorTime = -Infinity;
  authority.objects.forEach((expected, index) => {
    const observed = actual[index];
    if (!observed) return;
    for (const key of ['order', 'phase', 'key']) {
      if (observed[key] !== expected[key]) failures.push(`COS upload ledger object ${index + 1} ${key} mismatch`);
    }
    if (observed.uploadStatus !== 'PASS') failures.push(`COS upload ledger object ${expected.key} is not PASS`);
    if (!isCanonicalUtcIso(observed.uploadedAt, { allowPending: false })) {
      failures.push(`COS upload ledger object ${expected.key} uploadedAt is not canonical UTC ISO`);
    } else {
      const time = Date.parse(observed.uploadedAt);
      if (time <= priorTime) failures.push(`COS upload ledger order is not strictly increasing at ${expected.key}`);
      priorTime = time;
    }
  });
  if (!isCanonicalUtcIso(ledger?.uploadCompletedAt, { allowPending: false })) {
    failures.push('COS upload ledger uploadCompletedAt is not canonical UTC ISO');
  } else if (Date.parse(ledger.uploadCompletedAt) <= priorTime) {
    failures.push('COS upload ledger uploadCompletedAt must follow every upload');
  }
  return { status: failures.length === 0 ? 'GREEN' : 'RED_STOP_LINE', failures };
}

export function validateCosEvidence(authority, evidence, uploadLedger) {
  const failures = [];
  if (evidence?.schemaVersion !== 2) failures.push('COS evidence schemaVersion must be 2');
  if (evidence?.generatedBy !== 'scripts/verify-cos-assets.mjs') {
    failures.push('COS evidence must be generated by scripts/verify-cos-assets.mjs');
  }
  if (evidence?.authoritySha256 !== cosAuthoritySha256(authority)) {
    failures.push('COS evidence authority digest mismatch');
  }
  const ledgerResult = validateCosUploadLedger(authority, uploadLedger);
  if (ledgerResult.status !== 'GREEN') {
    failures.push(`COS upload ledger: ${ledgerResult.failures.join('; ')}`);
  }
  if (evidence?.uploadLedgerSha256 !== cosUploadLedgerSha256(uploadLedger)) {
    failures.push('COS evidence upload ledger digest mismatch');
  }
  if (evidence?.version !== authority.version) failures.push('COS evidence version mismatch');
  if (evidence?.baseUrl !== authority.baseUrl) failures.push('COS evidence baseUrl mismatch');
  if (!['payload-first-metadata-last', 'manual-payloads-only'].includes(authority?.sequencing)) {
    failures.push('COS authority sequencing mismatch');
  }
  if (evidence?.sequencing !== authority.sequencing) failures.push('COS evidence sequencing mismatch');
  if (findPendingFields(evidence).length > 0) failures.push('COS evidence contains pending placeholders');

  const actual = evidence?.objects ?? [];
  if (actual.length !== authority.objects.length) {
    failures.push(`COS evidence object count mismatch: ${actual.length}/${authority.objects.length}`);
  }
  let priorTime = -Infinity;
  authority.objects.forEach((expected, index) => {
    const observed = actual[index];
    const ledgerObject = uploadLedger?.objects?.[index];
    if (!observed) return;
    for (const key of ['order', 'phase', 'key', 'bytes', 'sha256']) {
      if (observed[key] !== expected[key]) {
        failures.push(`COS object ${index + 1} ${key} mismatch`);
      }
    }
    if (observed.uploadStatus !== 'PASS' || observed.verifyStatus !== 'PASS') {
      failures.push(`COS object ${expected.key} is not uploaded and verified`);
    }
    if (
      observed.uploadStatus !== ledgerObject?.uploadStatus
      || observed.uploadedAt !== ledgerObject?.uploadedAt
    ) failures.push(`COS evidence upload ledger object mismatch: ${expected.key}`);
    if (!isCanonicalUtcIso(observed.uploadedAt, { allowPending: false })) {
      failures.push(`COS object ${expected.key} uploadedAt is not canonical UTC ISO`);
    } else {
      const time = Date.parse(observed.uploadedAt);
      if (time <= priorTime) failures.push(`COS upload order is not strictly increasing at ${expected.key}`);
      priorTime = time;
    }
    if (expected.phase === 'metadata' && index < 4) {
      failures.push(`COS metadata object ${expected.key} was not sequenced after all payloads`);
    }
    const expectedRangeBytes = Math.min(1024, expected.bytes);
    const expectedContentRange = `bytes 0-${expectedRangeBytes - 1}/${expected.bytes}`;
    if (
      observed.headStatus !== 200
      || observed.contentLength !== expected.bytes
      || observed.rangeStatus !== 206
      || observed.contentRange !== expectedContentRange
      || observed.rangeBytes !== expectedRangeBytes
      || observed.fullBytes !== expected.bytes
      || observed.fullSha256 !== expected.sha256
    ) {
      failures.push(`COS network verification mismatch: ${expected.key}`);
    }
  });
  if (!isCanonicalUtcIso(evidence?.uploadCompletedAt, { allowPending: false })) {
    failures.push('COS uploadCompletedAt is not canonical UTC ISO');
  } else if (Date.parse(evidence.uploadCompletedAt) <= priorTime) {
    failures.push('COS uploadCompletedAt must follow every upload');
  }
  if (evidence?.uploadCompletedAt !== uploadLedger?.uploadCompletedAt) {
    failures.push('COS evidence uploadCompletedAt does not match the upload ledger');
  }
  if (!isCanonicalUtcIso(evidence?.verificationCompletedAt, { allowPending: false })) {
    failures.push('COS verificationCompletedAt is not canonical UTC ISO');
  } else if (
    isCanonicalUtcIso(evidence?.uploadCompletedAt, { allowPending: false })
    && Date.parse(evidence.verificationCompletedAt) <= Date.parse(evidence.uploadCompletedAt)
  ) {
    failures.push('COS verificationCompletedAt must follow uploadCompletedAt');
  }

  return {
    status: failures.length === 0 ? 'GREEN' : 'RED_STOP_LINE',
    failures,
    objectCount: actual.length,
  };
}
